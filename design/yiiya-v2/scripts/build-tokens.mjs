#!/usr/bin/env node
// Generates design/yiiya-v2/tokens.css from tokens.json.
// Usage: node design/yiiya-v2/scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));

/** Flatten primitive groups into CSS-friendly names. */
export function flattenPrimitives(primitive) {
  const out = {};
  for (const [group, values] of Object.entries(primitive)) {
    for (const [key, value] of Object.entries(values)) {
      const name = group === "color" || group === "size" ? key : `${group}-${key}`;
      out[name] = value;
    }
  }
  return out;
}

const ref = /\{([a-z0-9-]+)\}/gi;
const toVar = (value) => String(value).replace(ref, (_, name) => `var(--yi-${name})`);

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) build();

function build() {
const primitives = flattenPrimitives(tokens.primitive);
const lines = [];
lines.push("/* GENERATED by scripts/build-tokens.mjs from tokens.json — do not edit by hand. */");
lines.push("/* Layers: primitive (raw) -> semantic (per theme) -> component. */");
lines.push("");
lines.push(":root {");
for (const [name, value] of Object.entries(primitives)) lines.push(`  --yi-${name}: ${value};`);
lines.push("}");
lines.push("");

const block = (selector, theme) => {
  lines.push(`${selector} {`);
  lines.push(`  color-scheme: ${theme === "light" ? "light" : "dark"};`);
  for (const [name, value] of Object.entries(tokens.semantic[theme])) {
    lines.push(`  --yi-${name}: ${toVar(value)};`);
  }
  lines.push("}");
  lines.push("");
};

block(':root,\n[data-theme="dark"]', "dark");
block('[data-theme="light"]', "light");
// System preference applies only when the user has not chosen a theme.
lines.push("@media (prefers-color-scheme: light) {");
lines.push("  :root:not([data-theme]) {");
lines.push("    color-scheme: light;");
for (const [name, value] of Object.entries(tokens.semantic.light)) {
  lines.push(`    --yi-${name}: ${toVar(value)};`);
}
lines.push("  }");
lines.push("}");
lines.push("");

lines.push(":root {");
for (const [name, value] of Object.entries(tokens.component)) lines.push(`  --yi-${name}: ${toVar(value)};`);
lines.push("}");
lines.push("");

lines.push("@media (prefers-reduced-motion: reduce) {");
lines.push("  :root {");
for (const key of Object.keys(tokens.primitive.duration)) {
  if (key !== "instant") lines.push(`    --yi-duration-${key}: 0ms;`);
}
lines.push("  }");
lines.push("}");
lines.push("");

writeFileSync(join(root, "tokens.css"), lines.join("\n"));
console.log(`tokens.css written: ${Object.keys(primitives).length} primitives, ` +
  `${Object.keys(tokens.semantic.dark).length} semantic/theme, ${Object.keys(tokens.component).length} component.`);
}
