#!/usr/bin/env node
// Validates WCAG 2.x contrast for every pair in tokens.json, in both themes,
// plus selection-outline visibility against representative object materials.
// Writes contrast-report.md and exits 1 if any required pair fails.
// Usage: node design/yiiya-v2/scripts/check-contrast.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { flattenPrimitives } from "./build-tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));
const primitives = flattenPrimitives(tokens.primitive);

function resolve(value, theme, depth = 0) {
  if (depth > 8) throw new Error(`Reference loop at ${value}`);
  const m = /^\{([a-z0-9-]+)\}$/i.exec(String(value).trim());
  if (!m) return value;
  const name = m[1];
  if (tokens.semantic[theme][name] !== undefined) return resolve(tokens.semantic[theme][name], theme, depth + 1);
  if (primitives[name] !== undefined) return resolve(primitives[name], theme, depth + 1);
  throw new Error(`Unknown token {${name}}`);
}

function hexToRgb(hex) {
  const h = hex.replace("#", "");
  if (!/^[0-9a-f]{6}$/i.test(h)) throw new Error(`Not an opaque hex colour: ${hex}`);
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}
function luminance(hex) {
  const [r, g, b] = hexToRgb(hex).map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function ratio(a, b) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

const rows = [];
let failures = 0;
for (const theme of ["dark", "light"]) {
  for (const pair of tokens.contrastPairs) {
    const fg = resolve(`{${pair.fg}}`, theme);
    const bg = resolve(`{${pair.bg}}`, theme);
    const r = ratio(fg, bg);
    const pass = r >= pair.min;
    if (!pass) failures++;
    rows.push({ theme, ...pair, fgHex: fg, bgHex: bg, r, pass });
  }
}

const matRows = [];
for (const theme of ["dark", "light"]) {
  const outline = resolve("{selection}", theme);
  const haloLight = resolve("{selection-halo-light}", theme);
  const haloDark = resolve("{selection-halo-dark}", theme);
  for (const [name, hex] of Object.entries(tokens.materialSelectionChecks.materials)) {
    // The halo is luminance-adaptive: the renderer picks whichever halo contrasts more.
    const halo = Math.max(ratio(haloLight, hex), ratio(haloDark, hex));
    const best = Math.max(ratio(outline, hex), halo);
    const pass = best >= 3;
    if (!pass) failures++;
    matRows.push({ theme, name, hex, outline: ratio(outline, hex), halo, best, pass });
  }
}

const fmt = (n) => n.toFixed(2);
const md = [];
md.push("# Contrast report (generated)");
md.push("");
md.push("Generated by `scripts/check-contrast.mjs` from `tokens.json`. WCAG 2.x relative-luminance");
md.push("ratios. Text pairs require 4.5:1; non-text UI boundaries, focus and selection require 3:1.");
md.push("This validates token pairs only — it does not prove every rendered composition passes.");
md.push("");
md.push(`Result: **${failures === 0 ? "PASS" : `FAIL (${failures})`}** — ${rows.length} token pairs, ${matRows.length} material checks.`);
md.push("");
md.push("| Theme | Use | Foreground | Background | Ratio | Min | Result |");
md.push("| --- | --- | --- | --- | --- | --- | --- |");
for (const r of rows) {
  md.push(`| ${r.theme} | ${r.use} | \`${r.fg}\` ${r.fgHex} | \`${r.bg}\` ${r.bgHex} | ${fmt(r.r)} | ${r.min} | ${r.pass ? "pass" : "**FAIL**"} |`);
}
md.push("");
md.push("## Selection outline vs object materials");
md.push("");
md.push("The canvas selection uses a coloured outline plus a 1px luminance-adaptive halo (white or navy, whichever contrasts more with the material under it). At least one stroke must reach 3:1.");
md.push("");
md.push("| Theme | Material | Hex | Outline | Halo | Best | Result |");
md.push("| --- | --- | --- | --- | --- | --- | --- |");
for (const r of matRows) {
  md.push(`| ${r.theme} | ${r.name} | ${r.hex} | ${fmt(r.outline)} | ${fmt(r.halo)} | ${fmt(r.best)} | ${r.pass ? "pass" : "**FAIL**"} |`);
}
md.push("");
writeFileSync(join(root, "contrast-report.md"), md.join("\n"));

for (const r of rows.filter((x) => !x.pass)) {
  console.log(`FAIL ${r.theme} ${r.fg} on ${r.bg}: ${fmt(r.r)} < ${r.min}`);
}
for (const r of matRows.filter((x) => !x.pass)) {
  console.log(`FAIL ${r.theme} selection on ${r.name}: ${fmt(r.best)} < 3`);
}
console.log(`${failures === 0 ? "PASS" : "FAIL"}: ${rows.length} pairs, ${matRows.length} material checks, ${failures} failures.`);
process.exit(failures === 0 ? 0 : 1);
