import { describe, expect, it } from "vitest";
import { resolveViewerSource } from "./viewer-source";

describe("public viewer sources", () => {
  it("opens the relative proxy link generated by the share button", () => {
    const raw = `/api/3d/proxy?src=${encodeURIComponent("https://microsoft-trellis-2.hf.space/model.glb")}`;
    expect(resolveViewerSource(raw)).toBe(raw);
  });
  it("preserves a public mirrored artifact", () => {
    const raw = "https://store.public.blob.vercel-storage.com/model.glb";
    expect(resolveViewerSource(raw)).toBe(raw);
  });
  it.each(["", "/api/admin", "//attacker.test/model.glb", "javascript:alert(1)",
    "/api/3d/proxy?src=http://127.0.0.1", "/api/3d/proxy?src=https://attacker.test/model.glb",
    "/api/3d/proxy?src=%2Fapi%2F3d%2Fproxy%3Fsrc%3Dhttps%3A%2F%2Fexample.hf.space"])("rejects untrusted source %s", raw => {
    expect(resolveViewerSource(raw)).toBe("");
  });
});
