from __future__ import annotations

import base64
import json
import os
import tempfile
from pathlib import Path
from typing import Any

import modal


APP_NAME = "yiiya-cad-worker"
image = (
    modal.Image.debian_slim(python_version="3.11")
    .pip_install_from_requirements("requirements.txt")
)
app = modal.App(APP_NAME)


def unit_scale(unit: str | None) -> float:
    if unit == "cm":
        return 10.0
    if unit == "in":
        return 25.4
    return 1.0


def infer_dimensions(brief: dict[str, Any]) -> tuple[float, float, float]:
    dimensions = brief.get("dimensions") or {}
    scale = unit_scale(dimensions.get("unit"))
    width = float(dimensions.get("width") or 120.0) * scale
    depth = float(dimensions.get("depth") or width * 0.7) * scale
    height = float(dimensions.get("height") or 90.0) * scale
    return width, depth, height


def infer_shape(prompt: str, brief: dict[str, Any]) -> dict[str, Any]:
    text = prompt.lower()
    width, depth, height = infer_dimensions(brief)

    if "lamp" in text:
        return {
            "kind": "lamp",
            "base_radius": max(24.0, width * 0.18),
            "stem_height": max(120.0, height * 1.2),
            "shade_radius": max(45.0, width * 0.32),
            "shade_height": max(42.0, height * 0.4),
        }

    if "stool" in text or "chair" in text:
        return {
            "kind": "stool",
            "width": max(180.0, width),
            "depth": max(180.0, depth),
            "seat_height": max(240.0, height * 1.5),
            "leg_width": max(18.0, min(width, depth) * 0.08),
        }

    if (
        "bottle" in text
        or "mug" in text
        or "cup" in text
        or "cylinder" in text
    ):
        return {
            "kind": "cylinder",
            "radius": max(18.0, width * 0.18),
            "height": max(72.0, height),
        }

    return {
        "kind": "box",
        "width": max(60.0, width),
        "depth": max(40.0, depth),
        "height": max(24.0, height),
    }


def cadquery_script(spec: dict[str, Any]) -> str:
    header = [
        "# Auto-generated by Yiiya CAD worker",
        "import cadquery as cq",
        "",
    ]

    if spec["kind"] == "box":
        lines = [
            *header,
            f'result = cq.Workplane("XY").box({spec["width"]:.2f}, {spec["depth"]:.2f}, {spec["height"]:.2f})',
            "show_object(result)",
        ]
        return "\n".join(lines)

    if spec["kind"] == "cylinder":
        lines = [
            *header,
            f'result = cq.Workplane("XY").circle({spec["radius"]:.2f}).extrude({spec["height"]:.2f})',
            "show_object(result)",
        ]
        return "\n".join(lines)

    if spec["kind"] == "stool":
        offset_x = spec["width"] / 2 - spec["leg_width"] / 2 - 12
        offset_y = spec["depth"] / 2 - spec["leg_width"] / 2 - 12
        half_leg_drop = spec["seat_height"] / 2
        lines = [
            *header,
            f'seat = cq.Workplane("XY").box({spec["width"]:.2f}, {spec["depth"]:.2f}, {(spec["leg_width"] * 1.4):.2f})',
            f'leg = cq.Workplane("XY").box({spec["leg_width"]:.2f}, {spec["leg_width"]:.2f}, {spec["seat_height"]:.2f})',
            f"offset_x = {offset_x:.2f}",
            f"offset_y = {offset_y:.2f}",
            f"""legs = (
    leg.translate(( offset_x,  offset_y, -{half_leg_drop:.2f}))
    .union(leg.translate((-offset_x,  offset_y, -{half_leg_drop:.2f})))
    .union(leg.translate(( offset_x, -offset_y, -{half_leg_drop:.2f})))
    .union(leg.translate((-offset_x, -offset_y, -{half_leg_drop:.2f})))
)""",
            "result = seat.union(legs)",
            "show_object(result)",
        ]
        return "\n".join(lines)

    lines = [
        *header,
        f'base = cq.Workplane("XY").circle({spec["base_radius"]:.2f}).extrude(18)',
        f'stem = cq.Workplane("XY").circle({(spec["base_radius"] * 0.2):.2f}).extrude({spec["stem_height"]:.2f}).translate((0, 0, 18))',
        f"""shade = (
    cq.Workplane("XY")
    .circle({(spec["shade_radius"] * 0.42):.2f})
    .extrude({(spec["shade_height"] * 0.18):.2f})
    .union(
        cq.Workplane("XY")
        .circle({(spec["shade_radius"] * 0.72):.2f})
        .extrude({(spec["shade_height"] * 0.28):.2f})
        .translate((0, 0, {(spec["shade_height"] * 0.18):.2f}))
    )
    .union(
        cq.Workplane("XY")
        .circle({spec["shade_radius"]:.2f})
        .extrude({(spec["shade_height"] * 0.54):.2f})
        .translate((0, 0, {(spec["shade_height"] * 0.46):.2f}))
    )
    .translate((0, 0, {(spec["stem_height"] + 12):.2f}))
)""",
        "result = base.union(stem).union(shade)",
        "show_object(result)",
    ]
    return "\n".join(lines)


def cadquery_module():
    import cadquery as cq

    return cq


def build_model(spec: dict[str, Any]):
    cq = cadquery_module()

    if spec["kind"] == "box":
        return cq.Workplane("XY").box(spec["width"], spec["depth"], spec["height"])

    if spec["kind"] == "cylinder":
        return cq.Workplane("XY").circle(spec["radius"]).extrude(spec["height"])

    if spec["kind"] == "stool":
        seat = cq.Workplane("XY").box(
            spec["width"], spec["depth"], spec["leg_width"] * 1.4
        )
        leg = cq.Workplane("XY").box(
            spec["leg_width"], spec["leg_width"], spec["seat_height"]
        )
        offset_x = spec["width"] / 2 - spec["leg_width"] / 2 - 12
        offset_y = spec["depth"] / 2 - spec["leg_width"] / 2 - 12
        half_leg_drop = spec["seat_height"] / 2
        legs = (
            leg.translate((offset_x, offset_y, -half_leg_drop))
            .union(leg.translate((-offset_x, offset_y, -half_leg_drop)))
            .union(leg.translate((offset_x, -offset_y, -half_leg_drop)))
            .union(leg.translate((-offset_x, -offset_y, -half_leg_drop)))
        )
        return seat.union(legs)

    base = cq.Workplane("XY").circle(spec["base_radius"]).extrude(18)
    stem = (
        cq.Workplane("XY")
        .circle(spec["base_radius"] * 0.2)
        .extrude(spec["stem_height"])
        .translate((0, 0, 18))
    )
    shade = (
        cq.Workplane("XY")
        .circle(spec["shade_radius"] * 0.42)
        .extrude(spec["shade_height"] * 0.18)
        .union(
            cq.Workplane("XY")
            .circle(spec["shade_radius"] * 0.72)
            .extrude(spec["shade_height"] * 0.28)
            .translate((0, 0, spec["shade_height"] * 0.18))
        )
        .union(
            cq.Workplane("XY")
            .circle(spec["shade_radius"])
            .extrude(spec["shade_height"] * 0.54)
            .translate((0, 0, spec["shade_height"] * 0.46))
        )
        .translate((0, 0, spec["stem_height"] + 12))
    )
    return base.union(stem).union(shade)


def export_preview_glb(stl_path: Path) -> tuple[str | None, dict[str, Any]]:
    import trimesh

    mesh = trimesh.load_mesh(str(stl_path), force="mesh")

    if mesh.is_empty:
        return None, {}

    glb_bytes = mesh.export(file_type="glb")
    if isinstance(glb_bytes, str):
        glb_bytes = glb_bytes.encode("utf-8")

    return base64.b64encode(glb_bytes).decode("ascii"), {
        "triangleCount": int(len(mesh.faces)),
        "vertexCount": int(len(mesh.vertices)),
        "watertight": bool(mesh.is_watertight),
        "bounds": mesh.bounds.tolist(),
    }


def generate(payload: dict[str, Any]) -> dict[str, Any]:
    prompt = str(payload.get("prompt", "")).strip()
    brief = payload.get("brief") or {}

    if not prompt:
        raise ValueError("CAD worker expected a prompt.")

    spec = infer_shape(prompt, brief)
    script = cadquery_script(spec)
    model = build_model(spec)
    cq = cadquery_module()

    with tempfile.TemporaryDirectory(prefix="yiiya-cad-") as tmp:
        tmpdir = Path(tmp)
        step_path = tmpdir / "model.step"
        stl_path = tmpdir / "model.stl"
        py_path = tmpdir / "cadquery.py"

        py_path.write_text(script)
        cq.exporters.export(model, str(step_path))
        cq.exporters.export(model, str(stl_path))

        step_text = step_path.read_text()
        stl_base64 = base64.b64encode(stl_path.read_bytes()).decode("ascii")
        preview_glb_base64, preview_stats = export_preview_glb(stl_path)

    validation = [
        {
            "label": "Preview tessellation",
            "status": "ready" if preview_glb_base64 else "failed",
            "detail": "A worker-built preview GLB was generated from the CAD mesh."
            if preview_glb_base64
            else "Preview GLB export failed in the worker runtime.",
        },
        {
            "label": "CadQuery compile",
            "status": "ready",
            "detail": "CadQuery model built successfully.",
        },
        {
            "label": "STEP export",
            "status": "ready",
            "detail": "STEP artifact exported from the worker runtime.",
        },
        {
            "label": "STL export",
            "status": "ready",
            "detail": "STL artifact exported from the worker runtime.",
        },
        {
            "label": "Named features",
            "status": "ready" if brief.get("partSemantics") else "needs-work",
            "detail": "Requested named parts were preserved in the bounded CAD plan."
            if brief.get("partSemantics")
            else "Add named parts if you want feature-level handoff guidance.",
        },
    ]

    return {
        "provider": "cadquery-worker",
        "previewGlbBase64": preview_glb_base64,
        "previewStats": preview_stats,
        "scriptText": script,
        "stepText": step_text,
        "stlBase64": stl_base64,
        "dimensions": brief.get("dimensions") or {"unit": "mm"},
        "warnings": [
            "CAD lane remains intentionally bounded to hard-surface/product-style geometry."
        ],
        "validation": validation,
        "handoffNotes": [
            "Use the CadQuery script as the editable source candidate.",
            "STEP and STL were exported by the worker runtime.",
        ],
    }


@app.function(
    image=image,
    cpu=4,
    memory=8192,
    timeout=60 * 10,
    secrets=[modal.Secret.from_name("yiiya-cad-worker")],
)
@modal.fastapi_endpoint(method="POST")
def generate_endpoint(payload: dict[str, Any]) -> dict[str, Any]:
    return generate(payload)


@app.local_entrypoint()
def main(payload_path: str) -> None:
    payload = json.loads(Path(payload_path).read_text())
    result = generate(payload)
    print(json.dumps(result, indent=2))
